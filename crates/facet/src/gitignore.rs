//! `.gitignore` templates for game engines, appended to a repository's `.gitignore` with a
//! preview. Only rules the file does not already have are added, under a header comment.

use std::path::Path;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Template {
    Unity,
    Unreal,
}

impl Template {
    pub const ALL: [Self; 2] = [Self::Unity, Self::Unreal];

    pub fn label(self) -> &'static str {
        match self {
            Self::Unity => "Unity",
            Self::Unreal => "Unreal Engine",
        }
    }

    /// The rules, one per line (comments group them; only rules are compared).
    pub fn rules(self) -> &'static str {
        match self {
            Self::Unity => UNITY,
            Self::Unreal => UNREAL,
        }
    }
}

