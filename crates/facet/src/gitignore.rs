/// The block to append to `existing` for `template`: a header and every rule `existing` does
/// not already have. Empty when nothing is missing.
pub fn addition(existing: &str, template: Template) -> String {
    let present: std::collections::HashSet<&str> = existing.lines().map(str::trim).collect();
    let missing: Vec<&str> = template
        .rules()
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .filter(|rule| !present.contains(rule))
        .collect();
    if missing.is_empty() {
        return String::new();
    }
    let mut block = format!("# {} (added by Facet)\n", template.label());
    for rule in missing {
        block.push_str(rule);
        block.push('\n');
    }
    block
}

/// `existing` with `block` appended after a blank line, in the file's own line endings.
pub fn apply(existing: &str, block: &str) -> String {
    let crlf = existing.contains("\r\n");
    let mut text = existing.to_owned();
    if !text.is_empty() {
        if !text.ends_with('\n') {
            text.push_str(if crlf { "\r\n" } else { "\n" });
        }
        text.push_str(if crlf { "\r\n" } else { "\n" });
    }
    if crlf {
        text.push_str(&block.replace('\n', "\r\n"));
    } else {
        text.push_str(block);
    }
    text
}

/// What appending a template changed, for undo.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Written {
    /// The file before (`None`: there was no `.gitignore`).
    pub previous: Option<String>,
    /// The file as written.
    pub written: String,
}

/// Read `<root>/.gitignore` (`None` if there is none).
pub fn read(root: &Path) -> std::io::Result<Option<String>> {
    match std::fs::read_to_string(root.join(".gitignore")) {
        Ok(text) => Ok(Some(text)),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(error) => Err(error),
    }
}

/// Append `template`'s missing rules to `<root>/.gitignore`. `Ok(None)`: nothing was missing.
pub fn append(root: &Path, template: Template) -> std::io::Result<Option<Written>> {
    let previous = read(root)?;
    let block = addition(previous.as_deref().unwrap_or(""), template);
    if block.is_empty() {
        return Ok(None);
    }
    let written = apply(previous.as_deref().unwrap_or(""), &block);
    std::fs::write(root.join(".gitignore"), &written)?;
    Ok(Some(Written { previous, written }))
}

/// Undo [`append`]: put the previous file back, unless the file was edited since.
pub fn restore(root: &Path, change: &Written) -> std::io::Result<()> {
    let path = root.join(".gitignore");
    if read(root)?.as_deref() != Some(change.written.as_str()) {
        return Err(std::io::Error::other(
            ".gitignore was edited after the rules were added; it was left as it is",
        ));
    }
    match &change.previous {
        Some(text) => std::fs::write(path, text),
        None => std::fs::remove_file(path),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn only_missing_rules_are_added() {
        let existing = "# mine\r\n/[Ll]ibrary/\r\n*.sln\r\nnotes.txt";
        let block = addition(existing, Template::Unity);
        assert!(block.starts_with("# Unity (added by Facet)\n"));
        assert!(!block.contains("/[Ll]ibrary/"));
        assert!(!block.contains("*.sln"));
        assert!(block.contains("/[Tt]emp/\n"));
        assert!(!block.contains("# Generated"));

        let text = apply(existing, &block);
        assert!(text.starts_with(existing));
        assert!(text.contains("notes.txt\r\n\r\n# Unity (added by Facet)\r\n"));
        assert!(
            !text.replace("\r\n", "").contains('\n'),
            "mixed line endings"
        );
        // Applying again adds nothing.
        assert_eq!(addition(&text, Template::Unity), "");
    }

    #[test]
    fn templates_have_no_duplicate_rules() {
        for template in Template::ALL {
            let rules: Vec<&str> = template
                .rules()
                .lines()
                .filter(|line| !line.is_empty() && !line.starts_with('#'))
                .collect();
            let unique: std::collections::HashSet<_> = rules.iter().collect();
            assert_eq!(rules.len(), unique.len(), "{template:?}");
            assert_eq!(addition("", template).lines().count(), rules.len() + 1);
        }
    }

    #[test]
    fn append_and_restore_round_trip() {
        let dir = tempfile::tempdir().unwrap();
        // No .gitignore yet: undo removes the file again.
        let change = append(dir.path(), Template::Unreal).unwrap().unwrap();
        assert_eq!(change.previous, None);
        assert!(read(dir.path())
            .unwrap()
            .unwrap()
            .starts_with("# Unreal Engine"));
        assert_eq!(append(dir.path(), Template::Unreal).unwrap(), None);
        restore(dir.path(), &change).unwrap();
        assert_eq!(read(dir.path()).unwrap(), None);

        // An edited file is not overwritten by undo.
        std::fs::write(dir.path().join(".gitignore"), "*.log\n").unwrap();
        let change = append(dir.path(), Template::Unity).unwrap().unwrap();
        assert_eq!(change.previous.as_deref(), Some("*.log\n"));
        assert!(change.written.starts_with("*.log\n\n# Unity"));
        std::fs::write(dir.path().join(".gitignore"), "changed\n").unwrap();
        assert!(restore(dir.path(), &change).is_err());
        assert_eq!(read(dir.path()).unwrap().as_deref(), Some("changed\n"));
    }
}
